def draft_category_response(
    runtime: Any,
    case_id: str,
    custom_instructions: str = "",
    response_text: str = "",
    reviewer: str = "reviewer",
    chat_id: str | None = None,
    expected_version: int | None = None,
) -> dict[str, Any]:
    """Generate a category response draft and save in Gmail / compose lifecycle."""
    case = runtime.repository.get_case(case_id)
    if case is None:
        raise KeyError(case_id)
    if expected_version is not None and case.get("version") != expected_version:
        raise Conflict("Case version conflict; please refresh")

    category = case.get("category") or (case.get("result") or {}).get("category")
    original_subject = case.get("subject") or "General Inquiry"
    subject = (
        original_subject
        if original_subject.lower().startswith("re:")
        else f"Re: {original_subject}"
    )

    if response_text and len(response_text.strip()) > 5:
        body = response_text.strip()
    elif category == EmailCategory.INVOICE_QUERY.value:
        subject, body = generate_invoice_response_draft(case, custom_instructions)
    elif category == EmailCategory.GENERAL.value:
        subject, body = generate_general_response_draft(case, custom_instructions)
    else:
        subject, body = generate_general_response_draft(case, custom_instructions)

    updated = create_category_response_draft(
        runtime.repository,
        runtime.gmail,
        runtime.telegram,
        case,
        subject=subject,
        body=body,
        attachments=[],
        chat_id=chat_id,
        origin="template",
    )

    workflow_state = dict(case.get("workflow_state") or {})
    workflow_state.update({
        "stage": "DRAFT_PREPARED",
        "updated_at": utcnow().isoformat(),
        "updated_by": reviewer,
    })

    final_updated = runtime.repository.update_case(
        case_id,
        {"workflow_state": workflow_state},
        expected_version=updated.get("version"),
    )
    runtime.repository.append_event(
        case_id,
        "category_response_draft_created",
        {"category": category, "reviewer": reviewer},
    )
    return final_updated


