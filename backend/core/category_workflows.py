def extract_si_fields(
    subject: str,
    body: str,
    attachments: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    """Extract shipping instruction fields heuristically from subject, body, and text attachments."""
    combined_text = f"{subject}\n{body}"
    for att in attachments or []:
        text = att.get("text") or att.get("raw_text") or ""
        if text:
            combined_text += f"\n{text}"

    fields: dict[str, Any] = {
        "shipper": None,
        "consignee": None,
        "notify_party": None,
        "port_of_loading": None,
        "port_of_discharge": None,
        "container_count": None,
        "gross_weight_kg": None,
        "cargo_description": None,
    }

    # Regex patterns for shipping fields
    patterns = {
        "shipper": r"(?:shipper|exporter|from)\s*[:\-]\s*([^\n\r]+)",
        "consignee": r"(?:consignee|to)\s*[:\-]\s*([^\n\r]+)",
        "notify_party": r"(?:notify(?:\s*party)?)\s*[:\-]\s*([^\n\r]+)",
        "port_of_loading": r"(?:pol|port\s+of\s+loading|loading\s+port|origin)\s*[:\-]\s*([^\n\r]+)",
        "port_of_discharge": r"(?:pod|port\s+of\s+discharge|discharge\s+port|destination)\s*[:\-]\s*([^\n\r]+)",
        "container_count": r"(?:container(?:s)?\s*(?:count|qty|quantity)?|cntr)\s*[:\-]\s*(\d+)",
        "gross_weight_kg": r"(?:gross\s*weight|gw|total\s*weight)\s*[:\-]\s*([0-9.,]+)\s*(?:kgs?|kg|t|tons?)?",
        "cargo_description": r"(?:cargo|goods|commodity|description\s+of\s+goods)\s*[:\-]\s*([^\n\r]+)",
    }

    for key, pattern in patterns.items():
        match = re.search(pattern, combined_text, flags=re.IGNORECASE)
        if match:
            val = match.group(1).strip()
            if key == "container_count":
                try:
                    fields[key] = int(val)
                except ValueError:
                    fields[key] = 1
            elif key == "gross_weight_kg":
                clean_num = val.replace(",", "")
                try:
                    fields[key] = float(clean_num)
                except ValueError:
                    fields[key] = None
            else:
                fields[key] = val

    # Default fallback values if unparsed
    if not fields["port_of_loading"]:
        pol_match = re.search(r"\b(?:from|ex)\s+([A-Z][a-zA-Z\s]+?)(?:,\s*[A-Z]{2,})?\s+to\b", combined_text, flags=re.IGNORECASE)
        if pol_match:
            fields["port_of_loading"] = pol_match.group(1).strip()
    if not fields["port_of_discharge"]:
        pod_match = re.search(r"\bto\s+([A-Z][a-zA-Z\s]+?)(?:,\s*[A-Z]{2,})?(?:\.|\n|\r|$)", combined_text, flags=re.IGNORECASE)
        if pod_match:
            fields["port_of_discharge"] = pod_match.group(1).strip()

    return fields


def format_si_document_text(
    fields: dict[str, Any],
    case_id: str,
    subject: str,
    status: str = "DRAFT",
) -> str:
    """Format structured SI fields into a standard shipping instruction plain text document."""
    timestamp = datetime.now(UTC).strftime("%Y-%m-%d %H:%M:%S UTC")
    container_str = str(fields.get("container_count") or "TBD")
    weight_str = f"{fields.get('gross_weight_kg'):,.2f} kg" if fields.get("gross_weight_kg") is not None else "TBD"

    return f"""================================================================================
SHIPPING INSTRUCTION (SI)
Generated by ShipVerify Platform
Reference : SI-{case_id}
Subject   : {subject or 'Shipping Instruction'}
Date      : {timestamp}
Status    : {status.upper()}
================================================================================

1. SHIPPER / EXPORTER:
   {fields.get('shipper') or 'NOT SPECIFIED (PENDING CONFIRMATION)'}

2. CONSIGNEE:
   {fields.get('consignee') or 'TO ORDER (PENDING INSTRUCTION)'}

3. NOTIFY PARTY:
   {fields.get('notify_party') or 'SAME AS CONSIGNEE'}

4. PORT OF LOADING (POL):
   {fields.get('port_of_loading') or 'NOT SPECIFIED'}

5. PORT OF DISCHARGE (POD):
   {fields.get('port_of_discharge') or 'NOT SPECIFIED'}

6. CONTAINER COUNT:
   {container_str}

7. TOTAL GROSS WEIGHT:
   {weight_str}

8. CARGO & COMMODITY DESCRIPTION:
   {fields.get('cargo_description') or 'GENERAL CARGO / FREIGHT ALL KINDS (FAK)'}

================================================================================
SYSTEM VERIFICATION NOTES:
- This document was generated from customer instructions.
- Verification required before final transmission to ocean carrier.
================================================================================
END OF SHIPPING INSTRUCTION
"""


def generate_si_artifact(
    runtime: Any,
    case_id: str,
    fields: dict[str, Any] | None = None,
    reviewer: str = "system",
    expected_version: int | None = None,
) -> dict[str, Any]:
    """Generate SI text document, store artifact, and update case workflow state."""
    case = runtime.repository.get_case(case_id)
    if case is None:
        raise KeyError(case_id)

    if expected_version is not None and case.get("version") != expected_version:
        raise Conflict("Case version conflict; please refresh before generating SI")

    stored_documents = runtime.repository.list_documents(case_id)
    extracted = fields or extract_si_fields(
        case.get("subject", ""),
        case.get("body", ""),
        stored_documents,
    )

    doc_text = format_si_document_text(
        extracted,
        case_id=case_id,
        subject=case.get("subject", ""),
        status="GENERATED",
    )
    data = doc_text.encode("utf-8")
    sha256 = hashlib.sha256(data).hexdigest()

    filename = f"SI_{case_id}.txt"
    document_id = f"si-generated-{case_id}"
    gcs_uri = runtime.blobs.upload(f"cases/{case_id}/{filename}", data, content_type="text/plain")

    # Add as case document
    runtime.repository.add_document(
        case_id,
        document_id,
        {
            "filename": filename,
            "content_type": "text/plain",
            "size_bytes": len(data),
            "sha256": sha256,
            "gcs_uri": gcs_uri,
            "raw_text": doc_text,
            "extraction": {
                "document_type": "SI",
                "readable": True,
                "fields": extracted,
            },
        },
    )

    artifact_meta = SIArtifactMetadata(
        document_id=document_id,
        filename=filename,
        content_type="text/plain",
        gcs_uri=gcs_uri,
        size_bytes=len(data),
        sha256=sha256,
        status="generated",
    ).model_dump()

    workflow_state = {
        "category": EmailCategory.SI_REQUEST.value,
        "stage": "GENERATED",
        "assigned_team": "Documentation",
        "si_artifact": artifact_meta,
        "si_fields": extracted,
        "is_blocked": False,
        "updated_at": utcnow().isoformat(),
        "updated_by": reviewer,
    }

    updated = runtime.repository.update_case(
        case_id,
        {
            "workflow_state": workflow_state,
            "si_artifact": artifact_meta,
        },
        expected_version=case.get("version"),
    )
    runtime.repository.append_event(
        case_id,
        "si_artifact_generated",
        {"document_id": document_id, "filename": filename, "reviewer": reviewer},
    )
    return updated


def verify_si(
    runtime: Any,
    case_id: str,
    fields: dict[str, Any] | None = None,
    reviewer: str = "reviewer",
    note: str = "",
    expected_version: int | None = None,
) -> dict[str, Any]:
    """Mark the SI as verified and update fields if modified."""
    case = runtime.repository.get_case(case_id)
    if case is None:
        raise KeyError(case_id)
    if expected_version is not None and case.get("version") != expected_version:
        raise Conflict("Case version conflict; please refresh")

    workflow_state = dict(case.get("workflow_state") or {})
    si_fields = fields if fields is not None else workflow_state.get("si_fields", {})
    artifact = dict(workflow_state.get("si_artifact") or {})

    now = utcnow().isoformat()
    artifact["status"] = "verified"
    artifact["verified_at"] = now
    artifact["verified_by"] = reviewer

    workflow_state.update({
        "stage": "VERIFIED",
        "si_fields": si_fields,
        "si_artifact": artifact,
        "updated_at": now,
        "updated_by": reviewer,
    })

    updated = runtime.repository.update_case(
        case_id,
        {"workflow_state": workflow_state, "si_artifact": artifact},
        expected_version=case.get("version"),
    )
    runtime.repository.append_event(
        case_id,
        "si_verified",
        {"reviewer": reviewer, "note": note},
    )
    return updated


