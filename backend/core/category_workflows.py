def return_si_to_requester(
    runtime: Any,
    case_id: str,
    reviewer: str = "reviewer",
    chat_id: str | None = None,
    expected_version: int | None = None,
) -> dict[str, Any]:
    """Prepare a Gmail draft returning the approved SI document attachment to the requester."""
    case = runtime.repository.get_case(case_id)
    if case is None:
        raise KeyError(case_id)
    if expected_version is not None and case.get("version") != expected_version:
        raise Conflict("Case version conflict; please refresh")

    workflow_state = dict(case.get("workflow_state") or {})
    artifact = workflow_state.get("si_artifact") or case.get("si_artifact")
    if not artifact:
        raise ValueError("Cannot return SI: document has not been generated")

    filename = artifact.get("filename", f"SI_{case_id}.txt")
    gcs_uri = artifact.get("gcs_uri")
    doc_bytes = b""
    if gcs_uri:
        doc_bytes = runtime.blobs.download(gcs_uri)
    if not doc_bytes:
        doc_bytes = format_si_document_text(
            workflow_state.get("si_fields", {}),
            case_id,
            case.get("subject", ""),
            status="APPROVED",
        ).encode("utf-8")

    subject, body = generate_si_return_draft(case, filename)
    attachments = [(filename, "text/plain", doc_bytes)]

    updated = create_category_response_draft(
        runtime.repository,
        runtime.gmail,
        runtime.telegram,
        case,
        subject=subject,
        body=body,
        attachments=attachments,
        chat_id=chat_id,
        origin="template",
    )

    now = utcnow().isoformat()
    artifact_copy = dict(artifact)
    artifact_copy["status"] = "returned"
    artifact_copy["returned_at"] = now

    workflow_state.update({
        "stage": "RETURNED",
        "si_artifact": artifact_copy,
        "updated_at": now,
        "updated_by": reviewer,
    })

    final_updated = runtime.repository.update_case(
        case_id,
        {"workflow_state": workflow_state, "si_artifact": artifact_copy},
        expected_version=updated.get("version"),
    )
    runtime.repository.append_event(
        case_id,
        "si_returned_to_requester",
        {"reviewer": reviewer, "filename": filename},
    )
    return final_updated


