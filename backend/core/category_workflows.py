def block_sender_workflow(
    runtime: Any,
    case_id: str | None,
    sender: str,
    reviewer: str = "reviewer",
    reason: str = "",
    expected_version: int | None = None,
) -> dict[str, Any]:
    """Persist sender block, attempt Gmail filter creation, and update case state."""
    raw_sender = sender.strip()
    _, email_addr = parseaddr(raw_sender)
    target_sender = email_addr or raw_sender

    filter_id: str | None = None
    if getattr(runtime.gmail, "is_configured", False):
        try:
            filter_res = runtime.gmail.create_sender_filter(target_sender)
            filter_id = filter_res.get("id")
        except Exception as exc:
            logger.warning("Failed to create Gmail filter for %s: %s", target_sender, exc)

    record = runtime.repository.block_sender(target_sender, reason=reason, filter_id=filter_id)

    if case_id:
        case = runtime.repository.get_case(case_id)
        if case:
            if expected_version is not None and case.get("version") != expected_version:
                raise Conflict("Case version conflict; please refresh")
            workflow_state = dict(case.get("workflow_state") or {})
            workflow_state.update({
                "stage": "BLOCKED",
                "is_blocked": True,
                "block_reason": reason,
                "updated_at": utcnow().isoformat(),
                "updated_by": reviewer,
            })
            updated = runtime.repository.update_case(
                case_id,
                {"workflow_state": workflow_state, "is_blocked": True},
                expected_version=case.get("version"),
            )
            runtime.repository.append_event(
                case_id,
                "sender_blocked",
                {"sender": target_sender, "reviewer": reviewer, "filter_id": filter_id},
            )
            return updated

    return record


def unblock_sender_workflow(
    runtime: Any,
    sender: str,
) -> bool:
    """Remove sender block from repository and delete Gmail filter if possible."""
    raw_sender = sender.strip()
    _, email_addr = parseaddr(raw_sender)
    target_sender = email_addr or raw_sender

    blocked_list = runtime.repository.list_blocked_senders()
    matching = next((b for b in blocked_list if b.get("sender") == target_sender.lower()), None)
    filter_id = (matching or {}).get("filter_id")

    if filter_id and getattr(runtime.gmail, "is_configured", False):
        try:
            runtime.gmail.delete_filter(filter_id)
        except Exception as exc:
            logger.warning("Failed to delete Gmail filter %s: %s", filter_id, exc)

    return runtime.repository.unblock_sender(target_sender)


def mark_not_spam_workflow(
    runtime: Any,
    case_id: str,
    reviewer: str = "reviewer",
    reclassify_as: EmailCategory = EmailCategory.GENERAL,
    expected_version: int | None = None,
) -> dict[str, Any]:
    """Unmark spam, unblock sender if blocked, and reclassify case."""
    case = runtime.repository.get_case(case_id)
    if case is None:
        raise KeyError(case_id)
    if expected_version is not None and case.get("version") != expected_version:
        raise Conflict("Case version conflict; please refresh")

    sender = case.get("sender", "")
    if sender and runtime.repository.is_sender_blocked(sender):
        unblock_sender_workflow(runtime, sender)

    workflow_state = dict(case.get("workflow_state") or {})
    now = utcnow().isoformat()
    workflow_state.update({
        "category": reclassify_as.value,
        "stage": "NOT_SPAM",
        "is_blocked": False,
        "updated_at": now,
        "updated_by": reviewer,
    })

    result = dict(case.get("result") or {})
    result["category"] = reclassify_as.value

    updated = runtime.repository.update_case(
        case_id,
        {
            "category": reclassify_as.value,
            "result": result,
            "workflow_state": workflow_state,
            "is_blocked": False,
        },
        expected_version=case.get("version"),
    )
    runtime.repository.append_event(
        case_id,
        "marked_not_spam",
        {"reviewer": reviewer, "reclassified_as": reclassify_as.value},
    )
    return updated


def build_default_workflow_state(case: dict[str, Any]) -> dict[str, Any]:
    """Build a default workflow state dictionary for a case if none is persisted."""
    cat = (case.get("category") or (case.get("result") or {}).get("category") or "GENERAL").upper()
    if cat == "SI_REQUEST" or cat == "NEW_SI_REQUEST":
        artifact = case.get("si_artifact")
        stage = "GENERATED" if artifact else "PENDING_GENERATION"
        return {
            "category": EmailCategory.SI_REQUEST.value,
            "stage": stage,
            "assigned_team": "Documentation",
            "si_artifact": artifact,
            "si_fields": {},
            "is_blocked": False,
        }
    if cat == "INVOICE_QUERY":
        return {
            "category": EmailCategory.INVOICE_QUERY.value,
            "stage": "RECEIVED",
            "assigned_team": "Finance",
            "is_blocked": False,
        }
    if cat == "SPAM":
        return {
            "category": EmailCategory.SPAM.value,
            "stage": "FLAGGED",
            "assigned_team": "Security",
            "is_blocked": bool(case.get("is_blocked")),
        }
    return {
        "category": EmailCategory.GENERAL.value,
        "stage": "RECEIVED",
        "assigned_team": "Customer Service",
        "is_blocked": False,
    }


def compute_available_actions(case: dict[str, Any], is_blocked: bool = False) -> list[str]:
    """Determine available category actions based on category and workflow stage."""
    cat = (case.get("category") or (case.get("result") or {}).get("category") or "").upper()
    state = case.get("workflow_state") or build_default_workflow_state(case)
    stage = state.get("stage", "")

    if cat in ("BL_COMPARISON", "DOCUMENT_COMPARISON"):
        return ["review", "prepare_draft", "approve", "decline"]

    if cat in ("SI_REQUEST", "NEW_SI_REQUEST"):
        if stage in ("PENDING_GENERATION", "RECEIVED", ""):
            return ["generate_si"]
        if stage == "GENERATED":
            return ["verify_si", "approve_si"]
        if stage == "VERIFIED":
            return ["approve_si", "verify_si"]
        if stage == "APPROVED":
            return ["return_si", "verify_si"]
        if stage == "RETURNED":
            return []
        return ["generate_si"]

    if cat == "INVOICE_QUERY":
        if stage in ("RECEIVED", ""):
            return ["route_finance", "draft_response"]
        if stage == "ROUTED":
            return ["draft_response", "complete"]
        if stage == "DRAFT_PREPARED":
            return ["complete", "draft_response"]
        if stage == "COMPLETED":
            return []
        return ["route_finance"]

    if cat == "GENERAL":
        if stage in ("RECEIVED", ""):
            return ["route_cs", "draft_response"]
        if stage == "ROUTED":
            return ["draft_response", "complete"]
        if stage == "DRAFT_PREPARED":
            return ["complete", "draft_response"]
        if stage == "COMPLETED":
            return []
        return ["route_cs"]

    if cat == "SPAM":
        if is_blocked or state.get("is_blocked"):
            return ["not_spam"]
        return ["block_sender", "not_spam"]

    return []
